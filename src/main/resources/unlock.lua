-- ============================================================================
-- 释放分布式锁的 Lua 脚本。
-- 作用：保证"比对锁归属 + 删除锁"两步原子完成，避免竞态：
--       线程A 的锁过期后被线程B 拿到，线程A 再来 del 会误删线程B 的锁。
-- 参数：KEYS[1]=锁key(如 lock:order:123), ARGV[1]=当前线程唯一标识(UUID前缀-线程id)
-- 返回：1=成功释放；0=不是自己的锁（不动）
-- ============================================================================

-- 锁里存的标识 == 我的标识，才允许删
if(redis.call('get', KEYS[1]) ==  ARGV[1]) then
    return redis.call('del', KEYS[1])
end
-- 不是我的锁（已过期被他人持有），什么都不做
return 0
